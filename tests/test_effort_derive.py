import pytest

from cfbench import config, paths, provenance
from cfbench.effort import derive as d

KEYS = (
    "input_tokens",
    "output_tokens",
    "cache_creation_5m",
    "cache_creation_1h",
    "cache_read_tokens",
)


def cell(rnd, stage, model, cost, **kw):
    base = {"round": rnd, "stage": stage, "model": model, "messages": 1, "input_tokens": 1, "output_tokens": 10,
            "cache_creation_5m": 2, "cache_creation_1h": 3, "cache_read_tokens": 100, "cost_usd": cost}  # fmt: skip
    return {**base, **kw}


def history():
    def rnd(n, stage_s, idle):
        return {
            "round": n, "tag": f"v{n}", "sha": f"s{n}",
            "wall_clock": {"attributed_seconds": sum(stage_s.values()), "idle_seconds": idle,
                           "by_stage": stage_s, "by_milestone": {"P0": 60, "other": sum(stage_s.values()) - 60}},
            "foundry": {"review_rounds": 2, "reviews": [{"round": 1, "verdict": "CHANGES REQUESTED", "fix_tasks": 1},
                                                        {"round": 2, "verdict": "APPROVED", "fix_tasks": 0}]},
            "defects": {"by_source": {"review": n}, "none": 4},
            "interventions": {"count": 1, "items": [{"when": "2026-09-30", "stage_task": "post-merge", "what": "tagged"}]},
            "tool_log": {"denied": {"count": n, "categories": {"recursive grep": n}}},
        }  # fmt: skip

    return {"gaps": ["human-interventions.md records when and what but not how long; durations are unavailable"],
            "rounds": [rnd(1, {"implement": 600, "review": 300}, 0), rnd(2, {"implement": 400, "untagged": 50}, 7200)]}  # fmt: skip


def usage(costs=(1.5, 2.5, 4.0)):
    return {
        "records": [{"stage_method": "agent type", "stage": "implement", "round": 1},
                    {"stage_method": "nearest preceding tool-log entry", "stage": "unknown", "round": 2}],
        "summary": [cell(1, "implement", "m-a", costs[0]), cell(1, "controller", "m-b", costs[1]),
                    cell(2, "implement", "m-a", costs[2])],
        "gaps": ["no price for model m-a (input_per_mtok unset in config/pricing.toml)", "usage covers only local transcripts"],
    }  # fmt: skip


def test_totals_equal_sum_of_rounds():
    t = d.build_tables(history(), usage(), None)
    totals = {r["round"]: r for r in t["effort_totals"]}
    assert set(totals) == {1, 2, "total"}
    for k in (
        "wall_clock_s",
        "idle_s",
        "input_tokens",
        "output_tokens",
        "cache_write_tokens",
        "cache_read_tokens",
    ):
        assert totals["total"][k] == totals[1][k] + totals[2][k], k
    assert totals["total"]["cost_usd"] == pytest.approx(1.5 + 2.5 + 4.0)
    assert totals[1]["cache_write_tokens"] == 2 * (2 + 3)  # two cells in round 1, 5m plus 1h each
    assert totals[1]["models"] == "m-a;m-b"
    stage = {(r["round"], r["stage"]): r for r in t["effort_stage_round"]}
    assert (
        stage[(1, "implement")]["wall_clock_s"] == 600
        and stage[(1, "implement")]["output_tokens"] == 10
    )
    assert (
        stage[(1, "controller")]["wall_clock_s"] is None
    )  # tokens only: no commit stage for the main session
    assert (
        stage[(2, "untagged")]["wall_clock_s"] == 50
        and "output_tokens" not in stage[(2, "untagged")]
    )
    assert (
        sum(r["wall_clock_s"] or 0 for r in t["effort_stage_round"])
        == totals["total"]["wall_clock_s"]
    )
    assert [r["milestone"] for r in t["effort_milestones"] if r["round"] == 1] == ["P0", "other"]
    assert {r["review_rounds"] for r in t["effort_milestones"]} == {2}
    assert [r["verdict"] for r in t["effort_review_rounds"] if r["round"] == 2] == [
        "CHANGES REQUESTED",
        "APPROVED",
    ]
    assert {(r["round"], r["source"]): r["count"] for r in t["effort_defects"]}[(2, "review")] == 2
    assert t["effort_interventions"][0]["nature"] == "tagged"
    assert {(r["round"], r["category"]): r["count"] for r in t["effort_denied"]} == {
        (1, "recursive grep"): 1,
        (2, "recursive grep"): 2,
    }


def test_null_cost_propagates_and_is_listed_in_gaps():
    t = d.build_tables(history(), usage(costs=(None, 2.5, 4.0)), None)
    stage = {(r["round"], r["stage"]): r for r in t["effort_stage_round"]}
    assert stage[(1, "implement")]["cost_usd"] is None
    assert stage[(1, "controller")]["cost_usd"] == 2.5
    totals = {r["round"]: r for r in t["effort_totals"]}
    assert (
        totals[1]["cost_usd"] is None and totals["total"]["cost_usd"] is None
    )  # unknown stays unknown
    assert totals[2]["cost_usd"] == 4.0
    md = d.gaps_markdown(history(), usage(costs=(None, 2.5, 4.0)))
    assert md.startswith("<!-- generated by cfbench.effort.derive; do not edit -->")
    assert "no price for model m-a" in md and "never guesses a price" in md
    assert "durations are unavailable" in md  # intervention durations
    assert "unknown (1 records)" in md  # an unattributed stage is named
    assert "round 2: 50 s" in md and "idle_s" in md
    assert "agent type: 1" in md


def test_trajectory_join_pending_without_trajectory_table(tmp_path, monkeypatch):
    monkeypatch.setattr(paths, "RESULTS", tmp_path / "results")
    monkeypatch.setattr(paths, "RAW", tmp_path / "raw")
    from cfbench import rawio

    hp = rawio.write_raw(
        "effort",
        {"kind": "history", **history()},
        machine="any",
        profile="full",
        script="t",
        environment=None,
    )
    rawio.write_raw(
        "effort",
        {"kind": "usage", **usage()},
        machine="any",
        profile="full",
        script="t",
        environment=None,
    )
    d.derive()
    rows, side = provenance.read_table("trajectory_with_effort")
    assert rows == [] and side["pending"] == d.PENDING_TRAJECTORY
    assert provenance.read_table("effort_totals")[1]["pending"] is None
    assert hp.name in [
        e["path"].rsplit("/", 1)[-1] for e in provenance.read_table("effort_totals")[1]["raw_files"]
    ]
    # with a trajectory table the join carries per-round effort
    provenance.write_table(
        "trajectory", ["machine", "round", "tag", "sha", "corpus", "framing", "mode", "level", "agg_mib_s", "ratio_vs_zlib", "complete"],
        [{"machine": "M-B", "round": 2, "tag": "v2", "sha": "s2", "corpus": "silesia", "framing": "raw", "mode": "oneshot",
          "level": 6, "agg_mib_s": 100.0, "ratio_vs_zlib": 0.5, "complete": True}],
        script="t", raw_files=[],
    )  # fmt: skip
    d.derive()
    rows, side = provenance.read_table("trajectory_with_effort")
    assert side["pending"] is None and len(rows) == 1
    assert (
        rows[0]["round"] == "2"
        and float(rows[0]["wall_clock_s"]) == 450
        and float(rows[0]["cost_usd"]) == 4.0
    )
    assert (paths.RESULTS / "EFFORT_GAPS.md").exists()


def test_no_raw_data_writes_pending_for_every_table(tmp_path, monkeypatch):
    monkeypatch.setattr(paths, "RESULTS", tmp_path / "results")
    monkeypatch.setattr(paths, "RAW", tmp_path / "none")
    d.derive()
    for name in d.TABLES:
        rows, side = provenance.read_table(name)
        assert rows == [] and side["pending"] == d.PENDING_RAW
    assert d.PENDING_RAW in (paths.RESULTS / "EFFORT_GAPS.md").read_text()
    assert config.load_config("full")["effort"]["idle_gap_hours"] == 3


def test_forbidden_read_audit_totals_and_verdicts():
    hist = history()
    hist["rounds"][0]["tool_log"]["forbidden_reads"] = {
        "read_calls": 10,
        "candidates": [
            {"ts": "t1", "tool": "Bash", "stage": "review", "task": None, "path": "/usr/include/zlib", "rule": "root"},
            {"ts": "t2", "tool": "Read", "stage": "implement", "task": "P1", "path": "/opt/zlib/x.c", "rule": "word"},
        ],
    }  # fmt: skip
    hist["rounds"][1]["tool_log"]["forbidden_reads"] = {"read_calls": 5, "candidates": []}
    verdicts = {"t1": {"verdict": d.NOT_A_READ, "note": "regex text"}}
    t = d.build_tables(hist, usage(), None, verdicts)
    total = next(r for r in t["effort_totals"] if r["round"] == "total")
    assert (total["read_calls"], total["forbidden_read_candidates"], total["forbidden_reads"]) == (
        15,
        2,
        1,
    )
    assert total["interventions"] == 2 and total["denied_calls"] == 3
    rows = {r["ts"]: r for r in t["effort_forbidden_reads"]}
    assert rows["t1"]["verdict"] == d.NOT_A_READ and rows["t1"]["note"] == "regex text"
    assert rows["t2"]["verdict"] == d.UNCLASSIFIED  # an unclassified candidate counts as a read
    # history without the audit leaves the audit columns empty, never zero
    plain = d.build_tables(history(), usage(), None)
    tot = next(r for r in plain["effort_totals"] if r["round"] == "total")
    assert "forbidden_reads" not in tot and plain["effort_forbidden_reads"] == []


