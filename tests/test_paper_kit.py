import re
import shutil
from pathlib import Path

import pytest

from cfbench import config, paths
from cfbench.kits import claims, paper, pipeline, pitch
from cfbench.kits import sections as sections_mod

FIX = Path(__file__).parent / "fixtures" / "results"
CFG = config.load_config("full")


@pytest.fixture
def results(tmp_path):
    d = tmp_path / "results"
    shutil.copytree(FIX, d)
    return d


def sections(md: str) -> dict[str, str]:
    parts = re.split(r"^## ", md, flags=re.MULTILINE)[1:]
    return {p.split("\n", 1)[0]: p.split("\n", 1)[1] for p in parts}


def test_kit_sections_present(results):
    md = paper.render(results, CFG, results / "figures")
    assert md.startswith("<!-- generated by cfbench.kits.paper; do not edit -->")
    sec = sections(md)
    assert list(sec) == [
        "Claims and evidence",
        "Summary table",
        "Figure",
        "Supporting evidence (not for the paper body)",
        "Checked and not claimed",
        "Threats to validity",
        "Environments",
    ]
    assert md.splitlines()[2] == f"# Paper kit (T1): {pipeline.PIPELINE_NAME}"
    assert "![paper_throughput_unsafe](figures/paper_throughput_unsafe.png)" in sec["Figure"]
    assert (
        "no SIMD" in sec["Summary table"] and "no SIMD" in sec["Figure"]
    )  # the parity note on both
    heads = sec["Claims and evidence"]
    assert (
        re.search(r"^1\. \*\*Supported\*\*", heads, flags=re.MULTILINE)
        and "Source: `results/" in heads
    )
    assert "target 5-7" not in heads  # the fixtures support at least 5, so no shortfall note
    # the claims lead in category order, each with its question
    titles = re.findall(r"^### (.+)$", heads, flags=re.MULTILINE)
    assert titles == ["Equivalence", "Safety", "Clean-room", "Effort", "Viability", "Iteration"]
    assert pipeline.thesis() in heads
    sup = sec["Supporting evidence (not for the paper body)"]
    for sub in (
        "Viability on both machines",
        "Hardware-CRC evidence",
        "Sleep-interruption check",
        "Run-to-run stability",
    ):
        assert f"### {sub}" in sup
    threats = sec["Threats to validity"]
    for t in sections_mod.THREAT_TITLES:
        assert f"**{t}.**" in threats
    assert "| Metric | cf | zlib | mox |" in sec["Summary table"]
    assert (results / "figures" / "paper_throughput_unsafe.png").exists()


def test_shortfall_is_stated_explicitly(tmp_path):
    empty = tmp_path / "empty"
    empty.mkdir()
    md = paper.render(empty, CFG, tmp_path / "figs")
    heads = sections(md)["Claims and evidence"]
    assert "0 supported, target 5-7" in heads and "No claim is supported" in heads
    assert "Figure pending" in sections(md)["Figure"]
    assert "make conformance" in heads and "make perf" in heads and "make trajectory" in heads
    assert heads.count("**Pending**") == len(claims.MAIN)
    assert "No environment is recorded" in sections(md)["Environments"]


def test_every_number_in_claims_comes_from_evidence(results):
    md = paper.render(results, CFG, results / "figures")
    results_list = claims.evaluate(results, CFG)
    displays = {tok for c in results_list for e in c.evidence for tok in pitch.numbers(e.display)}
    # descriptors, not results: levels, round numbers and the "256" of SHA-256
    allowed = {
        str(x)
        for x in [
            *CFG["paper"]["perf_levels"],
            1,
            2,
            3,
            CFG["paper"]["trajectory_level"],
            256,
            "1.00",
        ]
    }
    marker = r"^\d+\. \*\*Supported\*\* \(`\w+`\): "
    bullets = [
        ln for ln in sections(md)["Claims and evidence"].splitlines() if re.match(marker, ln)
    ]
    assert len(bullets) >= 5
    for line in bullets:
        text = re.sub(marker, "", line)  # the list marker is not a claim number
        for run in pitch.numbers(text):
            assert run in displays or run in allowed, (run, line)
    # and the claim sentences are exactly the evaluated texts of the main claims
    assert [re.sub(marker, "", b) for b in bullets] == [
        c.text for c in results_list if c.status == "supported" and c.id in claims.MAIN
    ]


def test_render_is_deterministic(results):
    a = paper.render(results, CFG, results / "figures")
    b = paper.render(results, CFG, results / "figures")
    assert a == b
    svg1 = (results / "figures" / "paper_throughput_unsafe.svg").read_bytes()
    paper.render(results, CFG, results / "figures")
    assert svg1 == (results / "figures" / "paper_throughput_unsafe.svg").read_bytes()
    assert "20" not in re.sub(
        r"\d{8}T\d{6}Z", "", "".join(re.findall(r"timestamp[^\n]*", a))
    )  # no render timestamps


def test_rejected_section_lists_overreach_checks(results):
    md = paper.render(results, CFG, results / "figures")
    rej = sections(md)["Checked and not claimed"]
    for cid in ("parity_with_zlib", "faster_than_zrs"):
        assert f"**{cid}** (not supported)" in rej
    # every overreach check is stated whatever its outcome; the fixture data supports this one
    assert (
        "**faster_than_mox** (supported): cleanflate is faster than mox in every measured cell."
        in rej
    )
    # similarity is rejected when the statement disallows it, and the reason has no markdown noise
    (results / "similarity_statement.md").write_text("**T1 claim NOT allowed**: cf-mox between.\n")
    heads = sections(paper.render(results, CFG, results / "figures"))["Claims and evidence"]
    assert (
        "**Not supported** (`similarity`): T1 claim NOT allowed: cf-mox between. Scores:" in heads
    )
    # with no data at all every overreach check is rejected
    empty = results.parent / "empty"
    empty.mkdir()
    rej3 = sections(paper.render(empty, CFG, results.parent / "figs3"))["Checked and not claimed"]
    for cid in ("parity_with_zlib", "faster_than_zrs", "faster_than_mox"):
        assert f"**{cid}** (not supported): no data supports it" in rej3


