"""BLOG_NOTES.md: story beats with data callouts, ranked surprises and open questions (SPEC 5 T3).

These are notes for a human author, not a finished post. The story is the pipeline
(`pipeline.PIPELINE_NAME`); cleanflate is the worked example. The notes lead with the claims mapped
to evidence, in category order. Every number comes from an evidence lookup (`pitch.check_bullet`
enforces it); unfavourable results get the same prominence as favourable ones.
"""

import json
import sys
from pathlib import Path

from cfbench import config, paths
from cfbench.kits import claims as claims_mod
from cfbench.kits import evidence as ev
from cfbench.kits import pipeline, pitch, results_md, sections
from cfbench.kits.evidence import MissingData
from cfbench.kits.pipeline import CATEGORIES, EXAMPLE, PIPELINE_NAME
from cfbench.kits.pitch import Bullet, check_bullet

HEADER = "<!-- generated by cfbench.kits.blog; do not edit -->"
LEAD = "Claims and evidence"
BEATS = [
    "The pipeline and the question",
    "The worked example",
    "Equivalence",
    "Safety",
    "Clean-room",
    "Effort",
    "Viability on two machines",
    "The gzip and hardware-CRC story",
    "Iteration",
    "What zlib-rs took (context only)",
    "Limits",
]


def _bullets(items: list[Bullet]) -> list[str]:
    return [f"- {check_bullet(b).text}" for b in items]


def _loc_bullet(d: Path) -> list[Bullet]:
    code = pitch._look("loc", {"subject": "cf", "language": "Rust"}, "code", d, fmt="{:,.0f}")
    files = pitch._look("loc", {"subject": "cf", "language": "Rust"}, "files", d, fmt="{:.0f}")
    if code and files:
        return [
            Bullet(
                f"The cleanflate decompression path is {code.display} lines of Rust code in {files.display} files.",
                (code, files),
            )
        ]
    return []


def _zlibrs(d: Path) -> list[Bullet]:
    out = []
    for fact, text in (
        ("first_commit_date", "zlib-rs's first commit"),
        ("commit_count", "zlib-rs has accumulated this many commits"),
        ("contributor_count_including_anonymous", "zlib-rs's contributors, anonymous included"),
        ("first_github_release", "zlib-rs's first GitHub release"),
    ):
        e = pitch._look("zlibrs_context", {"fact": fact}, "value", d)
        if e:
            out.append(Bullet(f"{text}: {e.display}.", (e,)))
    scope = pitch._look("zlibrs_context", {"fact": "scope_note"}, "value", d)
    if scope:
        out.append(Bullet(scope.display, (scope,)))
    return out


def lead(d: Path, cfg: dict) -> list[str]:
    """The claims, in category order, each as an evidence-checked bullet."""
    by_cat = pitch.bullets_by_category(d, cfg)
    out = []
    for cat in CATEGORIES:
        out += [f"**{cat.title}.** *{cat.question}*", ""]
        out += _bullets(by_cat[cat.key]) or [f"- Pending: no data yet ({pitch.NO_DATA})."]
        out.append("")
    return out[:-1]


def beats(d: Path, cfg: dict) -> dict[str, list[str]]:
    claim = lambda ids: pitch.bullets_claims(ids, d, cfg)
    cross = pitch.bullets_crossmachine(d, cfg)
    return {
        BEATS[0]: [
            f"- {pipeline.thesis()}",
            (
                "- Notes only: state in your own words why a pipeline that turns RFCs into a memory-safe replacement "
                "for a legacy C library matters, and that one library is one data point (see Limits)."
            ),
        ],
        BEATS[1]: _bullets(
            [
                *pitch.bullets_unsafe(d, cfg)[:1],
                *_loc_bullet(d),
                Bullet(
                    f"{EXAMPLE} decompresses only and was built from the RFC texts alone under {PIPELINE_NAME}'s guard; "
                    "this benchmark repo lifts that rule and reads the comparators."
                ),
            ]
        ),
        BEATS[2]: _bullets(
            [
                *claim(["conformance", "fuzz", "malformed"]),
                *pitch.bullets_malformed(d, cfg),
                *pitch.bullets_fuzz(d, cfg),
            ]
        ),
        BEATS[3]: _bullets([*claim(["safety"]), *pitch.bullets_unsafe(d, cfg)[1:]]),
        BEATS[4]: _bullets([*claim(["isolation"]), *pitch.bullets_similarity(d, cfg)]),
        BEATS[5]: _bullets(
            [
                *claim(["effort"]),
                *[b for b in pitch.bullets_effort(d, cfg) if b.text.startswith("The agents")],
            ]
        ),
        BEATS[6]: _bullets(
            [
                *claim(["perf_range"]),
                *[b for b in cross if not b.text.startswith(("gzip minus raw", "Sleep check"))],
                *claim(["parity_with_zlib", "faster_than_zrs", "faster_than_mox"]),
            ]
        ),
        BEATS[7]: _bullets(
            [
                *[b for b in cross if b.text.startswith("gzip minus raw")],
                *claim(["gzip_gap_is_hw_crc"]),
                *pitch.bullets_checksums(d, cfg),
            ]
        ),
        BEATS[8]: _bullets(
            [*claim(["trajectory"]), *[b for b in cross if b.text.startswith("Sleep check")]]
        ),
        BEATS[9]: _bullets(_zlibrs(d)),
        BEATS[10]: [f"- {t}" for t in THREAT_TITLES],
    }


THREAT_TITLES = sections.THREAT_TITLES


# ---- surprises -------------------------------------------------------------------------------


def surprises(d: Path, cfg: dict) -> list[Bullet]:
    """Ranked: comparator bugs, malformed disagreements, unexpected hypotheses, ratio outliers, flags."""
    out: list[Bullet] = []
    try:
        rows, _ = ev.table_rows("fuzz_divergences", d)
        for r in [r for r in rows if r["classification"] == "comparator-bug"]:
            e = pitch._look(
                "fuzz_divergences",
                {"artifact_sha256": r["artifact_sha256"]},
                "outcomes_by_subject",
                d,
            )
            if e:
                out.append(
                    Bullet(
                        f"Fuzzing found a comparator bug candidate on {r['target']}: {e.display}.",
                        (e,),
                    )
                )
    except MissingData:
        pass
    try:
        rows, _ = ev.table_rows("malformed_disagreements", d)
        machines = list(dict.fromkeys(r.get("machine", "") for r in rows))
        for m in machines:
            mine = [r for r in rows if r.get("machine", "") == m]
            examples = []
            for r in mine[:3]:
                where = {"machine": m, "file": r["file"]} if m else {"file": r["file"]}
                f = pitch._look("malformed_disagreements", where, "file", d)
                if f:
                    examples.append(f)
            on = f" on {m}" if m else ""
            out.append(
                Bullet(
                    f"Mature libraries disagree on accept versus reject for {len(mine)} malformed files{on} "
                    f"(row count of malformed_disagreements.csv); examples: {', '.join(e.display for e in examples)}.",
                    tuple(examples),
                    (str(len(mine)),),
                )
            )
    except MissingData:
        pass
    try:
        rows, _ = ev.table_rows("content_hypotheses", d)
        for r in rows:
            if r["machine"] == "ALL" and r["verdict"] != "confirmed":
                v = pitch._look(
                    "content_hypotheses",
                    {"hypothesis": r["hypothesis"], "machine": "ALL", "feature": "(combined)"},
                    "verdict",
                    d,
                )
                if v:
                    out.append(
                        Bullet(
                            f"Hypothesis {r['hypothesis'].lower()} did not come out confirmed: {v.display}.",
                            (v,),
                            (r["hypothesis"][1:],),
                        )
                    )
    except MissingData:
        pass
    out += outliers(d, cfg)
    try:
        rows, _ = ev.table_rows("perf_agreement_summary", d)
        for r in rows:
            if r["verdict"] != "pass":
                key = {"machine": r["machine"], "variant": r["variant"]}
                e = pitch._look("perf_agreement_summary", key, "flagged_cells", d, fmt="{:.0f}")
                if e:
                    out.append(
                        Bullet(
                            f"Run-to-run agreement flagged {e.display} cells on {r['machine']} ({r['variant']}).",
                            (e,),
                        )
                    )
    except MissingData:
        pass
    return out


def outliers(d: Path, cfg: dict) -> list[Bullet]:
    """Top three best and worst per-file cf ratios against zlib (generic, one-shot, raw, level 6).

    Only files of the configured corpora count; the tiny-input prefixes measure setup cost and are
    reported in the RESULTS.md appendix instead.
    """
    try:
        rows, _ = ev.table_rows("perf_cells", d)
    except MissingData:
        return []
    corpora = set(cfg["perf"]["corpora"])
    sel = {}
    for r in rows:
        if (r["subject"], r["variant"], r["mode"], r["framing"], r["level"]) == ("cf", "generic", "oneshot", "raw", "6") \
                and r["ratio_vs_zlib"] != "" and r.get("corpus", "") in corpora:  # fmt: skip
            sel[(r["machine"], r["workload"])] = float(r["ratio_vs_zlib"])
    ranked = sorted(sel.items(), key=lambda kv: kv[1])
    picks = [("worst", kv) for kv in ranked[:3]] + [("best", kv) for kv in reversed(ranked[-3:])]
    out = []
    for label, ((m, w), _v) in picks:
        key = {
            "machine": m,
            "variant": "generic",
            "subject": "cf",
            "workload": w,
            "level": 6,
            "framing": "raw",
            "mode": "oneshot",
        }
        e = pitch._look("perf_cells", key, "ratio_vs_zlib", d, fmt="{:.2f}x")
        name = pitch._look("perf_cells", key, "workload", d)  # a file name may contain digits
        if e and name:
            out.append(
                Bullet(
                    f"Per-file {label} case on {m}: {name.display} at {e.display} of zlib's throughput (raw, level 6, one-shot).",
                    (e, name),
                    ("6",),
                )
            )
    return out


# ---- open questions --------------------------------------------------------------------------


def pending_tables(d: Path) -> list[tuple[str, str]]:
    out = []
    for p in sorted(d.glob("*.csv.provenance.json")):
        side = json.loads(p.read_text(encoding="utf-8"))
        if side.get("pending"):
            out.append((side["table"].removesuffix(".csv"), side["pending"]))
    return out


def open_questions(d: Path, cfg: dict) -> list[str]:
    items = []
    for c in claims_mod.evaluate(d, cfg):
        if c.status == claims_mod.PENDING:
            items.append(f"Claim `{c.id}` is pending: {c.reason}")
        elif c.status == claims_mod.REJECTED and c.reason and "no data supports it" not in c.reason:
            items.append(f"Claim `{c.id}` is rejected: {c.reason}")
    try:
        rows, _ = ev.table_rows("content_hypotheses", d)
        items += [f"Hypothesis {r['hypothesis']} is inconclusive across machines." for r in rows
                  if r["machine"] == "ALL" and r["verdict"] == "inconclusive"]  # fmt: skip
    except MissingData:
        items.append("Hypotheses H1 and H2 are pending (they need perf data on both machines).")
    items += [f"Pending table `{t}`: {why}" for t, why in pending_tables(d)]
    items += [f"Threat to validity: {t}" for t in THREAT_TITLES]
    return items


def render(results_dir: Path | None = None, cfg: dict | None = None) -> str:
    d = Path(results_dir) if results_dir else paths.RESULTS
    cfg = cfg or config.load_config("full")
    intro = (
        f"Notes for a human author, not a finished post. The story is {PIPELINE_NAME}, the pipeline; {EXAMPLE} "
        "is the worked example. Every number below has an evidence source in `RESULTS.md`; where a result is "
        "unfavourable it is stated plainly."
    )
    lines = [HEADER, "", f"# Blog notes: {PIPELINE_NAME}", "", intro, ""]
    lines += [f"## {LEAD}", "", *lead(d, cfg), ""]
    for title, bullets in beats(d, cfg).items():
        lines += [
            f"## {title}",
            "",
            *(bullets or [f"- Pending: no data yet ({pitch.NO_DATA})."]),
            "",
        ]
    lines += ["## Most surprising findings (ranked)", ""]
    s = [f"{i}. {check_bullet(b).text}" for i, b in enumerate(surprises(d, cfg), 1)]
    lines += s or [f"- None detected yet ({pitch.NO_DATA})."]
    lines += ["", "## Open questions", "", *[f"- {q}" for q in open_questions(d, cfg)], ""]
    lines += [results_md.PARITY_NOTE, ""]
    return "\n".join(lines)


def main() -> int:
    out = paths.RESULTS / "BLOG_NOTES.md"
    out.write_text(render(), encoding="utf-8")
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
