"""PITCH_KIT: slide-sized figures plus a data-backed TALKING_POINTS.md (SPEC 5 T2, 2.4).

`python -m cfbench.kits.pitch` re-renders every available figure at slide size (16:9) into
`results/PITCH_KIT/` and writes `TALKING_POINTS.md`. Every number in a bullet comes from a
`kits.evidence` lookup; `check_bullet` refuses a bullet whose numbers are not in its evidence
displays. Figures whose tables are pending are not rendered and are listed with the reason.
"""

import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

from cfbench import charts, config, framing, more_charts, paths, perf_charts, provenance, trajectory
from cfbench.kits import claims as claims_mod
from cfbench.kits import evidence as ev
from cfbench.kits.evidence import Evidence, MissingData
from cfbench.parity import PARITY_NOTE
from cfbench.similarity import summary as similarity_summary

HEADER = "<!-- generated by cfbench.kits.pitch; do not edit -->"
MIN_FIGURES, MAX_FIGURES = 8, 12
NO_DATA = "no measurement in this study"
_NUMBER = re.compile(r"(?<![A-Za-z0-9_@])\d(?:[\d,]*\d)?(?:\.\d+)?")


@dataclass(frozen=True)
class Bullet:
    text: str
    evidence: tuple[Evidence, ...] = ()
    labels: tuple[str, ...] = ()  # configuration values (levels, thresholds) the text may quote


def check_bullet(b: Bullet) -> Bullet:
    """Raise unless every number in the text appears in an evidence display or a label."""
    shown = " ".join([e.display for e in b.evidence] + list(b.labels))
    allowed = set(_NUMBER.findall(shown))
    for token in _NUMBER.findall(b.text):
        if token not in allowed and not any(token in a for a in allowed):
            raise ValueError(f"number {token!r} in {b.text!r} has no evidence")
    return b


def numbers(text: str) -> list[str]:
    return _NUMBER.findall(text)


def _look(table, where, column, d, **kw) -> Evidence | None:
    try:
        return ev.lookup(table, where, column, results_dir=d, **kw)
    except MissingData:
        return None


# ---- figure rendering at slide size ----------------------------------------------------------


@dataclass
class Figure:
    key: str
    title: str
    stems: list[str] = field(default_factory=list)
    reason: str = ""

    @property
    def rendered(self) -> bool:
        return bool(self.stems)


def _pending(table: str, d: Path) -> str:
    try:
        ev.table_rows(table, d)
    except MissingData as e:
        return str(e)
    return f"table {table} has no usable rows"


def _stems(files: list[Path] | None) -> list[str]:
    return sorted({p.stem for p in files}) if files else []


def _typed(rows: list[dict], floats=(), ints=()) -> list[dict]:
    out = []
    for r in rows:
        t = dict(r)
        for k in floats:
            t[k] = provenance.to_float(r[k])
        for k in ints:
            t[k] = int(r[k])
        out.append(t)
    return out


def render_trajectory(d: Path, out: Path, cfg: dict) -> Figure:
    fig = Figure("trajectory", "Improvement by round")
    try:
        rows, _ = ev.table_rows("trajectory", d)
    except MissingData as e:
        fig.reason = str(e)
        return fig
    typed = _typed(rows, floats=("ratio_vs_zlib",), ints=("round", "level"))
    for machine in cfg["paper"]["machines"]:
        with charts.size_override("slide"):
            got = trajectory.figure(typed, machine, out_dir=out)
        fig.stems += _stems(got)
    if not fig.stems:
        fig.reason = "no trajectory ratios on any machine"
    return fig


def render_throughput(d: Path, out: Path, cfg: dict) -> Figure:
    fig = Figure("throughput", "Throughput against every comparator")
    try:
        ev.table_rows("perf_aggregates", d)
    except MissingData as e:
        fig.reason = str(e)
        return fig
    for machine in cfg["paper"]["machines"]:
        with charts.size_override("slide"):
            fig.stems += _stems(perf_charts.throughput_figure(machine, "generic", out_dir=out))
    if not fig.stems:
        fig.reason = "perf_aggregates holds no one-shot level-6 aggregates"
    return fig


def render_framing(d: Path, out: Path, cfg: dict) -> Figure:
    fig = Figure("framing", "Framing decomposition")
    try:
        rows, _ = ev.table_rows("framing_overhead", d)
    except MissingData as e:
        fig.reason = str(e)
        return fig
    typed = _typed(rows, floats=("overhead_zlib", "overhead_gzip"), ints=("level",))
    data = framing.figure_data(typed, cfg)
    if not data:
        fig.reason = "framing_overhead has no rows at the figure corpus and level"
        return fig
    with charts.size_override("slide"):
        files = charts.save_figure(framing.draw(data, cfg), framing.FIGURE,
                                   parity_note=PARITY_NOTE, size="default", out_dir=out)  # fmt: skip
    fig.stems = _stems(files)
    return fig


def render_similarity(d: Path, out: Path, cfg: dict) -> Figure:
    fig = Figure("similarity", "Similarity against the controls")
    try:
        rows, _ = ev.table_rows("similarity_summary", d)
    except MissingData as e:
        fig.reason = str(e)
        return fig
    typed = _typed(rows, floats=("score", "position"))
    with charts.size_override("slide"):
        files = charts.save_figure(similarity_summary.draw(typed), similarity_summary.FIGURE,
                                   parity_note=PARITY_NOTE, size="default", out_dir=out)  # fmt: skip
    fig.stems = _stems(files)
    return fig


def _more(key: str, title: str, fn_name: str):
    def render(d: Path, out: Path, cfg: dict) -> Figure:
        fig = Figure(key, title)
        with charts.size_override("slide"):
            fig.stems = _stems(getattr(more_charts, fn_name)(out))
        if not fig.stems:
            fig.reason = more_charts.PENDING_REASONS.get(key, "no data")
        return fig

    return render


def render_content(d: Path, out: Path, cfg: dict) -> Figure:
    """The content scatter plots exist only once perf data and content features are joined."""
    from cfbench.content import correlate

    fig = Figure("content", "Content features against the cf ratio")
    try:
        cells, _ = ev.table_rows("perf_cells", d)
        feats, _ = provenance.read_table("content_features", d)
    except (MissingData, FileNotFoundError) as e:
        fig.reason = str(e) or "content_features missing"
        return fig
    joined = correlate.join(cells, feats)
    if not joined:
        fig.reason = (
            "no cf perf cells join the content features: run `make perf` then `make content`"
        )
        return fig
    with charts.size_override("slide"):
        for m in sorted({r["machine"] for r in joined}):
            for h, (_desc, fts) in correlate.HYPOTHESES.items():
                for feat in fts[:1]:
                    fig.stems += _stems(correlate.scatter(joined, m, feat, h, out))
    if not fig.stems:
        fig.reason = "no content scatter could be drawn"
    return fig


RENDERERS = [
    render_trajectory,
    render_throughput,
    render_framing,
    render_similarity,
    _more("unsafe_counts", "Unsafe code", "unsafe_counts"),
    _more("binary_size", "Binary size", "binary_size"),
    _more("effort_cost_per_stage", "Effort per stage", "effort_cost_per_stage"),
    _more("malformed_highlights", "Malformed-input highlights", "malformed_highlights"),
    _more("fuzz_stats", "Fuzzing statistics", "fuzz_stats"),
    _more("checksum_throughput", "Checksum throughput", "checksum_throughput"),
    render_content,
]


def render_figures(d: Path, out: Path, cfg: dict) -> list[Figure]:
    out.mkdir(parents=True, exist_ok=True)
    figs = [r(d, out, cfg) for r in RENDERERS]
    kept, count = [], 0
    for f in figs:  # at most MAX_FIGURES figure files; extras are listed as not included
        n = len(f.stems)
        if f.rendered and count + n > MAX_FIGURES:
            for s in f.stems:
                for ext in ("svg", "png"):
                    (out / f"{s}.{ext}").unlink(missing_ok=True)
            f = Figure(f.key, f.title, [], f"left out: the kit holds at most {MAX_FIGURES} figures")
            n = 0
        count += n
        kept.append(f)
    return kept


# ---- bullets ---------------------------------------------------------------------------------


def _kib(v: float) -> str:
    return f"{v / 1024:.0f} KiB"


def bullets_unsafe(d: Path, cfg: dict) -> list[Bullet]:
    out = []
    blocks = _look(
        "unsafe", {"subject": "cf", "crate": "cleanflate"}, "unsafe_blocks", d, fmt="{:.0f}"
    )
    fns = _look("unsafe", {"subject": "cf", "crate": "cleanflate"}, "unsafe_fns", d, fmt="{:.0f}")
    forbid = _look("unsafe", {"subject": "cf", "crate": "cleanflate"}, "forbid_unsafe_code", d)
    if blocks and fns:
        text = f"cleanflate has {blocks.display} unsafe blocks and {fns.display} unsafe functions"
        text += (
            " and forbids unsafe code at its crate root."
            if forbid and forbid.display == "true"
            else "."
        )
        out.append(Bullet(text, tuple(x for x in (blocks, fns, forbid) if x)))
    zb = _look("unsafe", {"subject": "zrs", "crate": "zlib-rs"}, "unsafe_blocks", d, fmt="{:.0f}")
    zf = _look("unsafe", {"subject": "zrs", "crate": "zlib-rs"}, "unsafe_fns", d, fmt="{:.0f}")
    if zb and zf:
        out.append(Bullet(f"zlib-rs, the closest Rust comparator, has {zb.display} unsafe blocks and "
                          f"{zf.display} unsafe functions in its core crate.", (zb, zf)))  # fmt: skip
    out.append(Bullet("zlib and zlib-ng are C, so the whole codebase is memory-unsafe by language and no "
                      "count applies."))  # fmt: skip
    return out


def bullets_binary_size(d: Path, cfg: dict) -> list[Bullet]:
    m = cfg["paper"]["table_machine"]
    got = {s: _look("binary_size", {"machine": m, "subject": s, "opt": cfg["paper"]["table_opt"]}, "bytes", d,
                    fmt=_kib) for s in ("cf", "zlib", "zrs", "mox")}  # fmt: skip
    out = []
    if got["cf"] and got["zlib"]:
        bigger = got["cf"].value > got["zlib"].value
        out.append(Bullet(
            f"At opt-level {cfg['paper']['table_opt']} the stripped cleanflate decoder is {got['cf'].display} "
            f"against {got['zlib'].display} for zlib, so cleanflate's binary is "
            f"{'larger' if bigger else 'not larger'} than the C library's.",
            (got["cf"], got["zlib"]), (cfg["paper"]["table_opt"],)))  # fmt: skip
    rust = [(s, e) for s, e in got.items() if s in ("zrs", "mox") and e]
    if got["cf"] and rust:
        parts = ", ".join(f"{s} {e.display}" for s, e in rust)
        out.append(Bullet(f"Among the Rust decoders: cleanflate {got['cf'].display}, {parts}.",
                          (got["cf"], *[e for _s, e in rust])))  # fmt: skip
    return out


def bullets_effort(d: Path, cfg: dict) -> list[Bullet]:
    hours = _look(
        "effort_totals",
        {"round": "total"},
        "wall_clock_s",
        d,
        fmt="{:.1f}",
        transform=lambda s: s / 3600,
    )
    cost = _look("effort_totals", {"round": "total"}, "cost_usd", d, fmt="${:,.0f}")
    outt = _look("effort_totals", {"round": "total"}, "output_tokens", d, fmt="{:,.0f}")
    out = []
    if hours:
        out.append(
            Bullet(
                f"Three rounds took {hours.display} hours of attributed wall-clock time.", (hours,)
            )
        )
    if outt:
        out.append(
            Bullet(f"The agents wrote {outt.display} output tokens across all stages.", (outt,))
        )
    out.append(Bullet(f"Cost: {cost.display} estimated." if cost else "Cost is not priced in this study "
                      "(see EFFORT_GAPS.md), so no dollar figure is given.", (cost,) if cost else ()))  # fmt: skip
    return out


def bullets_malformed(d: Path, cfg: dict) -> list[Bullet]:
    try:
        rows, _ = ev.table_rows("malformed_disagreements", d)
    except MissingData:
        return []
    out = []
    for r in rows[:2]:
        f = _look("malformed_disagreements", {"file": r["file"]}, "file", d)
        exp = _look("malformed_disagreements", {"file": r["file"]}, "cf_expected", d)
        if f and exp:
            out.append(Bullet(f"{f.display}: cleanflate rejects it ({exp.display}) while other subjects "
                              "accept it, by design of its strict defaults.", (f, exp)))  # fmt: skip
    out.append(Bullet("Every disagreement is cleanflate being stricter than the comparators; none is a "
                      "comparator rejecting what cleanflate accepts."
                      if rows and all(r["outcomes_by_subject"].startswith("cf=error") for r in rows)
                      else "Some disagreements are not cleanflate being stricter; see the matrix."))  # fmt: skip
    return out


def bullets_fuzz(d: Path, cfg: dict) -> list[Bullet]:
    try:
        rows, _ = ev.table_rows("fuzz_stats", d)
    except MissingData:
        return []
    out = []
    for r in rows[:3]:
        key = {"machine": r["machine"], "target": r["target"]}
        e = _look("fuzz_stats", key, "executions", d, fmt="{:,.0f}")
        v = _look("fuzz_stats", key, "divergences", d, fmt="{:.0f}")
        if e and v:
            out.append(
                Bullet(
                    f"{r['target']} on {r['machine']}: {e.display} executions, {v.display} divergences.",
                    (e, v),
                )
            )
    return out


def bullets_similarity(d: Path, cfg: dict) -> list[Bullet]:
    res = next((c for c in claims_mod.evaluate(d, cfg) if c.id == "similarity"), None)
    out = []
    if res is not None and res.status == claims_mod.REJECTED:
        out.append(
            Bullet(
                f"The generated statement does NOT allow the independence claim: {res.reason.rstrip('.')}.",
                (),
            )
        )
    elif res is not None and res.status == claims_mod.SUPPORTED:
        out.append(Bullet(res.text, tuple(res.evidence)))
    ev_ = {p: _look("similarity_summary", {"metric": "ident_jaccard", "pair": p}, "score", d, fmt="{:.3f}")
           for p in ("zrs-mox", "zrs-zng", "cf-zrs", "cf-mox")}  # fmt: skip
    if ev_["zrs-mox"] and ev_["cf-zrs"] and ev_["cf-mox"]:
        out.append(Bullet(
            f"Identifier Jaccard: the independent pair zrs-mox scores {ev_['zrs-mox'].display}; cf-zrs scores "
            f"{ev_['cf-zrs'].display} and cf-mox {ev_['cf-mox'].display}.",
            tuple(x for x in (ev_["zrs-mox"], ev_["cf-zrs"], ev_["cf-mox"]) if x)))  # fmt: skip
    if ev_["zrs-zng"]:
        out.append(
            Bullet(
                f"The derived-work control zrs-zng scores {ev_['zrs-zng'].display}.",
                (ev_["zrs-zng"],),
            )
        )
    return out


def bullets_claims(ids: list[str], d: Path, cfg: dict) -> list[Bullet]:
    out = []
    p = cfg["paper"]
    labels = tuple(
        str(x) for x in (p["parity_ratio"], p["figure_level"], *p["perf_levels"], 1, 2, 3, "1.00")
    )
    for c in claims_mod.evaluate(d, cfg):
        if c.id not in ids:
            continue
        if c.status == claims_mod.SUPPORTED and c.text:
            out.append(Bullet(c.text, tuple(c.evidence), labels))
        elif c.status == claims_mod.REJECTED:
            out.append(Bullet(f"Not claimed ({c.id}): {c.reason}.", tuple(c.evidence), labels))
    return out


def bullets_checksums(d: Path, cfg: dict) -> list[Bullet]:
    m = cfg["paper"]["table_machine"]
    size = max(cfg["framing"]["checksum_sizes"])
    out = []
    for algo in ("crc32", "adler32"):
        got = {s: _look("checksums", {"machine": m, "subject": s, "algo": algo, "size": size}, "median_gib_s", d,
                        fmt="{:.2f} GiB/s") for s in ("cf", "zlib")}  # fmt: skip
        if got["cf"] and got["zlib"]:
            out.append(Bullet(f"{algo} at the largest input on {m}: cleanflate {got['cf'].display}, zlib {got['zlib'].display}.",
                              (got["cf"], got["zlib"])))  # fmt: skip
    return out


def bullets_content(d: Path, cfg: dict) -> list[Bullet]:
    out = []
    for h in ("H1", "H2"):
        v = _look(
            "content_hypotheses",
            {"hypothesis": h, "machine": "ALL", "feature": "(combined)"},
            "verdict",
            d,
        )
        if v:
            out.append(Bullet(f"Hypothesis {h.lower()} verdict: {v.display}.", (v,), (h[1:],)))
    return out


BULLETS = {
    "trajectory": lambda d, c: bullets_claims(["trajectory"], d, c),
    "throughput": lambda d, c: bullets_claims(["perf_range", "parity_with_zlib", "faster_than_zrs", "faster_than_mox"], d, c),
    "framing": lambda d, c: bullets_claims(["gzip_gap_is_hw_crc"], d, c),
    "similarity": bullets_similarity,
    "unsafe_counts": bullets_unsafe,
    "binary_size": bullets_binary_size,
    "effort_cost_per_stage": bullets_effort,
    "malformed_highlights": bullets_malformed,
    "fuzz_stats": bullets_fuzz,
    "checksum_throughput": bullets_checksums,
    "content": bullets_content,
}  # fmt: skip


# ---- Q&A -------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Answer:
    question: str
    bullets: list[Bullet]
    no_data: list[str]


def _framing_bullet(d: Path) -> Bullet | None:
    v = _look("framing_hypothesis", {"machine": "ALL"}, "verdict", d)
    if v:
        return Bullet(
            f"On the gzip-framing gap, the hardware-CRC explanation is {v.display}.", (v,)
        )
    return None


def answer_slower(d: Path, cfg: dict) -> Answer:
    bullets = bullets_claims(["perf_range", "parity_with_zlib"], d, cfg)
    fb = _framing_bullet(d)
    if fb:
        bullets.append(fb)
    bullets.append(Bullet(PARITY_NOTE))
    missing = [] if any(b.evidence for b in bullets) else ["perf ratios and framing verdict"]
    return Answer("Why is it slower than C?", bullets, missing)


def answer_copied(d: Path, cfg: dict) -> Answer:
    bullets = bullets_similarity(d, cfg)
    miss = [] if bullets else ["similarity scores"]
    return Answer("How do you know it wasn't copied?", bullets, miss)


def answer_cost(d: Path, cfg: dict) -> Answer:
    bullets = bullets_effort(d, cfg)
    return Answer(
        "What does this cost?",
        bullets,
        [] if any(b.evidence for b in bullets) else ["effort totals"],
    )


def answer_airgap(d: Path, cfg: dict) -> Answer:
    bullets, missing = [], []
    try:
        rows, _ = ev.table_rows("effort_denied", d)
        net = [r for r in rows if r["category"] == "network lockdown"]
        got = [
            _look(
                "effort_denied",
                {"round": r["round"], "category": "network lockdown"},
                "count",
                d,
                fmt="{:.0f}",
            )
            for r in net
        ]
        got = [g for g in got if g]
        if got:
            total = ", ".join(g.display for g in got)
            bullets.append(Bullet(f"The tool logs record denied network commands (one count per round that had any): {total}. That shows the "
                                  "network lockdown was exercised, not that the build ran air-gapped.", tuple(got)))  # fmt: skip
    except MissingData:
        pass
    models = _look("effort_totals", {"round": "total"}, "models", d)
    if models and models.display:
        bullets.append(
            Bullet(f"Models used: {models.display}. Nothing here measures other models.", (models,))
        )
    if not bullets:
        missing.append("network use and model comparison")
    bullets.append(Bullet(f"Air-gapped operation and other models: {NO_DATA}."))
    return Answer("Can it run air-gapped / on other models?", bullets, missing)


QUESTIONS = [answer_slower, answer_copied, answer_cost, answer_airgap]


# ---- document --------------------------------------------------------------------------------


def render_document(figs: list[Figure], d: Path, cfg: dict) -> str:
    n = sum(len(f.stems) for f in figs)
    lines = [HEADER, "", "# Talking points", ""]
    if n < MIN_FIGURES:
        lines += [
            f"**Only {n} figures rendered; the kit aims for {MIN_FIGURES} to {MAX_FIGURES}.** Not rendered:",
            "",
        ]
        lines += [f"- {f.title}: {f.reason}" for f in figs if not f.rendered]
        lines.append("")
    else:
        lines += [f"{n} figures rendered.", ""]
    for f in figs:
        if not f.rendered:
            continue
        lines += [
            f"## {f.title}",
            "",
            "Files: " + ", ".join(f"`{s}.svg`/`{s}.png`" for s in f.stems),
            "",
        ]
        bullets = [check_bullet(b) for b in BULLETS[f.key](d, cfg)][:3] or [
            Bullet(f"No bullet: {NO_DATA}.")
        ]
        lines += [f"- {b.text}" for b in bullets] + [""]
    lines += ["## Questions a reviewer will ask", ""]
    for q in QUESTIONS:
        a = q(d, cfg)
        lines += [f"### {a.question}", ""]
        lines += [f"- {check_bullet(b).text}" for b in a.bullets]
        lines += [
            f"- Pending: {m} ({NO_DATA}; run the make targets in PAPER_KIT.md)." for m in a.no_data
        ]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def build(
    results_dir: Path | None = None, out_dir: Path | None = None, cfg: dict | None = None
) -> tuple[list[Figure], Path]:
    d = Path(results_dir) if results_dir else paths.RESULTS
    out = Path(out_dir) if out_dir else d / "PITCH_KIT"
    cfg = cfg or config.load_config("full")
    figs = render_figures(d, out, cfg)
    doc = out / "TALKING_POINTS.md"
    doc.write_text(render_document(figs, d, cfg), encoding="utf-8")
    return figs, doc


def rederive() -> None:
    """Rebuild every table the kit reads from committed raw data (no measurement)."""
    from cfbench import bombs, complexity, fuzzing, loc, malformed, size, unsafe_scan  # noqa: F401
    from cfbench.content import correlate, features
    from cfbench.kits import paper

    paper.rederive()
    malformed.derive()
    fuzzing.report("full")
    bombs.derive()
    loc.derive_table()
    complexity.derive()
    features.derive()
    correlate.run()


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else "render"
    if cmd == "rederive":
        rederive()
        return 0
    if cmd != "render":
        print("usage: cfbench.kits.pitch [rederive|render]", file=sys.stderr)
        return 2
    figs, doc = build()
    for f in figs:
        print(f"{f.title}: " + (", ".join(f.stems) if f.rendered else f"pending ({f.reason})"))
    print(doc)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
