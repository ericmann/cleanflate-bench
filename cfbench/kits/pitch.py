"""PITCH_KIT: slide-sized figures plus a data-backed TALKING_POINTS.md (SPEC 5 T2, 2.4).

`python -m cfbench.kits.pitch` re-renders every available figure at slide size (16:9) into
`results/PITCH_KIT/` and writes `TALKING_POINTS.md`. Every number in a bullet comes from a
`kits.evidence` lookup; `check_bullet` refuses a bullet whose numbers are not in its evidence
displays. Figures whose tables are pending are not rendered and are listed with the reason.
"""

