"""Render results/PAPER_KIT.md from the derived tables (SPEC 5 T1, 7 B5).

`python -m cfbench.kits.paper` first re-derives, from committed raw data only and with no
measurement, the tables the kit reads, then renders. Output is byte-identical on rerun.
"""

import sys
from collections import OrderedDict
from pathlib import Path

from cfbench import config, paths, rawio
from cfbench.kits import claims as claims_mod
from cfbench.kits import paper_assets, sections
from cfbench.kits.evidence import Evidence
from cfbench.kits.pipeline import PIPELINE_NAME

HEADER = "<!-- generated by cfbench.kits.paper; do not edit -->"
TARGET_LOW, TARGET_HIGH = 5, 7
FIGURE_NAME = "paper_throughput_unsafe"
CAPTION = (
    f"Aggregate one-shot decompression throughput (MiB/s) on the Silesia corpus, raw framing, level 6, "
    f"for cleanflate (cf, the decoder {PIPELINE_NAME} built), miniz_oxide (mox) and stock zlib, on each "
    "machine. Bars are annotated with the `unsafe` blocks plus functions in the decompression crate "
    "(C: memory-unsafe by language)."
)


def source_line(evid: list[Evidence]) -> str:
    """`Source: <table> <- <raw files> via <script>` for the evidence behind a claim."""
    groups: OrderedDict[tuple, None] = OrderedDict()
    for e in evid:
        groups[(e.table, e.script, e.raw_files)] = None
    parts = []
    for table, script, raws in groups:
        raw = ", ".join(f"`{r}`" for r in raws) or "no raw file"
        parts.append(f"`results/{table}.csv` <- {raw} via `{script}`")
    return "Source: " + "; ".join(parts)


def environments(evid: list[Evidence]) -> list[dict]:
    """Distinct machine environments from the raw files referenced by the evidence."""
    seen: dict[tuple, dict] = {}
    for raw in sorted({r for e in evid for r in e.raw_files}):
        p = paths.ROOT / raw
        if not p.exists():
            continue
        env = rawio.load_raw(p).get("environment") or {}
        os_ = env.get("os") or {}
        row = {
            "machine": env.get("machine"),
            "cpu": env.get("cpu_model"),
            "os": " ".join(x for x in (os_.get("name"), os_.get("version")) if x) or None,
            "kernel": env.get("kernel"),
        }
        if row["machine"] or row["cpu"]:
            seen[(row["machine"], row["cpu"], row["os"], row["kernel"])] = row
    return [seen[k] for k in sorted(seen, key=lambda k: tuple(str(x) for x in k))]


def render(
    results_dir: Path | None = None, cfg: dict | None = None, out_dir: Path | None = None
) -> str:
    d = Path(results_dir) if results_dir else paths.RESULTS
    cfg = cfg or config.load_config("full")
    results = claims_mod.evaluate(d, cfg)
    table = paper_assets.build_table(d, cfg)
    figure_paths, fig_evidence, fig_pending = paper_assets.build_figure(
        d, out_dir or d / "figures", cfg
    )
    lead = sections.claims_map(results, cfg)
    supported = [c for c in results if c.id in claims_mod.MAIN and c.status == claims_mod.SUPPORTED]
    out = [HEADER, "", f"# Paper kit (T1): {PIPELINE_NAME}", ""]
    out += [
        (
            "Every number below comes from a derived table, a committed raw file and a script; see the "
            "`Source:` line under each claim and table."
        ),
        "",
    ]
    out += ["## Claims and evidence", ""]
    n = len(supported)
    if n < TARGET_LOW:
        out += [
            (
                f"{n} supported, target {TARGET_LOW}-{TARGET_HIGH}. The remaining candidates are "
                "marked Not supported or Pending below."
            ),
            "",
        ]
    elif n > TARGET_HIGH:
        out += [
            f"{n} supported; the paper has room for {TARGET_LOW}-{TARGET_HIGH}, so choose among them.",
            "",
        ]
    if not supported:
        out += ["No claim is supported by the committed data yet.", ""]
    out += [lead.text, ""]
    out += ["## Summary table", "", table.to_markdown(), ""]
    pend_rows = [
        r.label for r in table.rows if any(c.status == "pending" for c in r.cells.values())
    ]
    if pend_rows:
        out += [
            "Pending rows (missing data, shown as `pending`): " + "; ".join(pend_rows) + ".",
            "",
        ]
    out += ["## Figure", ""]
    if figure_paths:
        out += [
            f"![{FIGURE_NAME}](figures/{FIGURE_NAME}.png)",
            "",
            f"Vector version: `figures/{FIGURE_NAME}.svg`.",
            "",
            CAPTION,
            "",
        ]
        out += [
            source_line(fig_evidence) if fig_evidence else "Source: see the summary table rows.",
            "",
        ]
        if fig_pending:
            out += ["Pending bars: " + "; ".join(fig_pending), ""]
    else:
        reasons = list(dict.fromkeys(r.split(": ", 1)[-1] for r in fig_pending)) or ["no data"]
        out += ["Figure pending: " + "; ".join(reasons) + ".", ""]
    out += [f"*{table.footnote}*", ""]
    viab = sections.viability_table(d, cfg)
    gap = sections.gzip_gap_block(d, cfg)
    sleep = sections.sleep_check_block(d, cfg)
    stab = sections.stability_block(d, cfg)
    simsup = sections.similarity_supplement(d, cfg)
    out += ["## Supporting evidence (not for the paper body)", ""]
    out += ["### Viability on both machines", "", viab.text, ""]
    out += ["### Hardware-CRC evidence: the gzip gap on each machine", "", gap.text, ""]
    out += ["### Sleep-interruption check (trajectory round 3 against perf)", "", sleep.text, ""]
    out += ["### Run-to-run stability", "", stab.text, ""]
    out += ["### Similarity: sensitivity analysis and reference pairs (both added after the pre-registered analysis)", "", simsup.text, ""]  # fmt: skip
    out += ["## Checked and not claimed", "", sections.overreach(results), ""]
    out += ["## Threats to validity", ""]
    out += [f"- **{t}.** {p}" for t, p, _e in sections.threats(d, cfg)]
    out += [""]
    all_evidence = lead.evidence + fig_evidence + viab.evidence + gap.evidence + sleep.evidence
    envs = environments(all_evidence)
    out += ["## Environments", ""]
    if envs:
        out += ["| Machine | CPU | OS | Kernel |", "|---|---|---|---|"]
        out += [
            f"| {e['machine'] or ''} | {e['cpu'] or ''} | {e['os'] or ''} | {e['kernel'] or ''} |"
            for e in envs
        ]
    else:
        out += ["No environment is recorded in the raw files referenced by the evidence."]
    out += [""]
    return "\n".join(out)


def rederive() -> None:
    """Rebuild the tables the kit reads from committed raw data (no measurement)."""
    from cfbench import (
        agreement,
        conformance,
        crossmachine,
        deps,
        fuzzing,
        malformed,
        perf_report,
        size,
        trajectory,
        unsafe_scan,
    )
    from cfbench.effort import derive as effort_derive
    from cfbench.similarity import summary

    perf_report.derive_all()
    agreement.derive()
    malformed.derive()
    fuzzing.report("full")
    size.derive_binary()
    unsafe_scan.derive_table()
    deps.derive_table()
    summary.derive()
    trajectory.derive()
    effort_derive.derive()
    conformance.derive()
    try:  # Phase 6 adds the framing tables
        from cfbench import framing

        framing.derive()
    except ImportError:
        pass
    crossmachine.derive()


def main() -> int:
    rederive()
    text = render()
    out = paths.RESULTS / "PAPER_KIT.md"
    out.write_text(text, encoding="utf-8")
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
