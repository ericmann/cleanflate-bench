"""Position cf's similarity scores against the negative and positive controls (SPEC 3.8)."""

import sys
from pathlib import Path

from cfbench import charts, config, parity, paths, provenance, rawio

COLUMNS = [
    "metric",
    "pair",
    "role",
    "score",
    "neg_score",
    "pos_score",
    "position",
    "classification",
]
KINDS = ("ngram", "identifiers", "comments", "jplag")
HEADER = "<!-- generated by cfbench.similarity.summary; do not edit -->"
UNSEPARATED = "controls not separated"
NO_POS = "positive control unavailable"
NO_NEG = "negative control unavailable"
PENDING = "Pending: run `make similarity`"
FIGURE = "similarity_controls"


def label(p: dict) -> str:
    return f"{p['left']}-{p['right']}"


def metric_names(cfg: dict) -> list[str]:
    sim = cfg["similarity"]
    names = [f"ngram_jaccard@{n}" for n in range(sim["ngram_min"], sim["ngram_max"] + 1)]
    names += [f"ngram_containment@{sim['ngram_min']}", "ident_jaccard", "ident_match_rate_left"]
    return names + ["comment_jaccard", "jplag_avg"]


def collect_scores(payloads: dict, cfg: dict) -> dict[str, dict[str, dict]]:
    """{metric: {pair label: {role, score}}} from the raw payloads (missing inputs are omitted)."""
    sim = cfg["similarity"]
    out: dict[str, dict[str, dict]] = {m: {} for m in metric_names(cfg)}

    def put(metric: str, pair: dict, score) -> None:
        if score is not None:
            out[metric][label(pair)] = {"role": pair["role"], "score": score}

    for p in payloads.get("ngram", {}).get("pairs", []):
        for r in p["results"]:
            put(f"ngram_jaccard@{r['n']}", p, r["jaccard"])
            if r["n"] == sim["ngram_min"]:
                put(f"ngram_containment@{r['n']}", p, r["containment"])
    for p in payloads.get("identifiers", {}).get("pairs", []):
        put("ident_jaccard", p, p["ident_jaccard"])
        put("ident_match_rate_left", p, p["ident_match_rate_left"])
    for p in payloads.get("comments", {}).get("pairs", []):
        put("comment_jaccard", p, p["jaccard"])
    for p in payloads.get("jplag", {}).get("pairs", []):
        if p.get("status") == "ok":
            put("jplag_avg", p, p["avg"])
    return out


def position(score: float, neg: float, pos: float) -> float:
    return (score - neg) / (pos - neg)


def classify(pos_value: float, near: float) -> str:
    """Band of a position: 0 is the negative control, 1 the positive control."""
    if pos_value < 0:
        return "below negative"
    if pos_value <= near:
        return "at or near negative"
    if pos_value > 1:
        return "above positive"
    if pos_value >= 1 - near:
        return "at or near positive"
    return "between"


OK_BANDS = {"below negative", "at or near negative"}


def summarize(scores: dict, cfg: dict) -> list[dict]:
    """One row per metric and pair: score, controls, position and classification."""
    near = cfg["similarity"]["near_fraction"]
    rows = []
    for metric, by_pair in scores.items():
        neg = next((v["score"] for v in by_pair.values() if v["role"] == "negative"), None)
        pos = next((v["score"] for v in by_pair.values() if v["role"] == "positive"), None)
        for lab, v in by_pair.items():
            row = {
                "metric": metric,
                "pair": lab,
                "role": v["role"],
                "score": v["score"],
                "neg_score": neg,
                "pos_score": pos,
                "position": None,
            }
            if v["role"] in ("negative", "positive"):
                row["classification"] = f"{v['role']} control"
                row["position"] = 0.0 if v["role"] == "negative" else 1.0
            elif neg is None:
                row["classification"] = NO_NEG
            elif pos is None:
                row["classification"] = NO_POS
            elif pos <= neg:
                row["classification"] = UNSEPARATED
            else:
                row["position"] = position(v["score"], neg, pos)
                row["classification"] = classify(row["position"], near)
            rows.append(row)
    return rows


def failing_metrics(rows: list[dict]) -> tuple[list[str], list[str]]:
    """(metrics where a cf test pair is not at or near negative or below, non-separable metrics)."""
    failing, unsep = set(), set()
    separable_seen = set()
    for r in rows:
        if r["role"] != "test":
            continue
        if r["classification"] in OK_BANDS:
            separable_seen.add(r["metric"])
        elif r["classification"] in (UNSEPARATED, NO_POS, NO_NEG):
            unsep.add(r["metric"])
        else:
            failing.add(r["metric"])
            separable_seen.add(r["metric"])
    return sorted(failing), sorted(unsep - separable_seen - failing)


def statement(rows: list[dict]) -> str:
    """The generated result statement. Deterministic for the same rows."""
    out = [HEADER, "", "# Similarity result statement", ""]
    if not rows:
        return "\n".join([*out, PENDING, ""])
    metrics = list(dict.fromkeys(r["metric"] for r in rows))
    for m in metrics:
        mr = [r for r in rows if r["metric"] == m]
        controls = {r["role"]: r for r in mr if r["role"] in ("negative", "positive")}
        tests = [r for r in mr if r["role"] == "test"]
        neg, pos = controls.get("negative"), controls.get("positive")
        head = f"- `{m}`: "
        head += (
            f"negative control {neg['pair']} {neg['score']:.4g}" if neg else "no negative control"
        )
        head += (
            f", positive control {pos['pair']} {pos['score']:.4g}."
            if pos
            else ", no positive control."
        )
        if not tests:
            out.append(head + " No cf pair scored.")
            continue
        parts = []
        for t in tests:
            if t["position"] is not None:
                parts.append(
                    f"{t['pair']} {t['score']:.4g} is {t['classification']} (position {t['position']:.2f})"
                )
            else:
                ratio = (
                    f", {t['score'] / neg['score']:.2f}x the negative control"
                    if neg and neg["score"]
                    else ""
                )
                parts.append(
                    f"{t['pair']} {t['score']:.4g} cannot be positioned ({t['classification']}{ratio})"
                )
        out.append(head + " " + "; ".join(parts) + ".")
    failing, unsep = failing_metrics(rows)
    out.append("")
    if failing:
        detail = []
        for m in failing:
            bad = [
                f"{r['pair']} {r['classification']}"
                for r in rows
                if r["metric"] == m and r["role"] == "test" and r["classification"] not in OK_BANDS
            ]
            detail.append(f"`{m}` ({'; '.join(bad)})")
        out.append(
            "**T1 claim NOT allowed**: a cf pair is not at or near the negative control for "
            + ", ".join(detail)
            + "."
        )
    elif unsep and len(unsep) == len(metrics):
        out.append("**T1 claim NOT allowed**: no metric separates the controls.")
    else:
        out.append(
            "**T1 claim allowed**: on every separable metric each cf pair sits at or near the "
            "negative control or below it."
        )
    if unsep:
        out.append("")
        out.append(
            "Metrics that do not separate the controls (excluded from the claim test): "
            + ", ".join(f"`{m}`" for m in unsep)
            + "."
        )
    out.append("")
    return "\n".join(out)


def load_inputs() -> tuple[dict, list[Path]]:
    """Newest raw document of each kind from similarity/any."""
    newest: dict[str, tuple[Path, dict]] = {}
    for p in rawio.list_raw("similarity", machine="any"):
        d = rawio.load_raw(p)
        kind = d["payload"].get("kind")
        if kind in KINDS and (kind not in newest or d["timestamp"] > newest[kind][1]["timestamp"]):
            newest[kind] = (p, d)
    return {k: v[1]["payload"] for k, v in newest.items()}, [v[0] for v in newest.values()]


def draw(rows: list[dict]):
    """Dot plot: one row per separable metric; x is position (negative control 0, positive 1)."""
    metrics = []
    for r in rows:
        if r["position"] is not None and r["role"] == "test" and r["metric"] not in metrics:
            metrics.append(r["metric"])
    fig = charts.new_figure("default")
    ax = fig.subplots()
    colors = ["#4C72B0", "#DD8452", "#55A868", "#C44E52"]
    pair_labels = list(dict.fromkeys(r["pair"] for r in rows if r["role"] == "test"))
    for y, m in enumerate(metrics):
        for i, lab in enumerate(pair_labels):
            for r in rows:
                if r["metric"] == m and r["pair"] == lab and r["position"] is not None:
                    ax.scatter(r["position"], y, color=colors[i % len(colors)], s=22, zorder=3,
                               label=lab if y == 0 else None)  # fmt: skip
    ax.axvline(0, color="#2a7", linewidth=1.2, label="negative control (zrs-mox)")
    ax.axvline(1, color="#c33", linewidth=1.2, label="positive control (zrs-zng)")
    ax.set_yticks(range(len(metrics)), metrics, fontsize=6)
    ax.set_xlabel("position between controls (0 = negative, 1 = positive)", fontsize=7)
    ax.tick_params(axis="x", labelsize=7)
    if metrics:
        ax.legend(fontsize=6, loc="upper center", bbox_to_anchor=(0.5, 1.2), ncol=3, frameon=False)
    else:
        ax.text(0.5, 0.5, "no metric separates the controls", ha="center", transform=ax.transAxes)
    fig.suptitle("Where cf falls between the independent and derived controls", fontsize=8)
    return fig


def derive() -> None:
    cfg = config.load_config("full")
    payloads, raw = load_inputs()
    script = "cfbench.similarity.summary"
    out_statement = paths.RESULTS / "similarity_statement.md"
    out_statement.parent.mkdir(parents=True, exist_ok=True)
    if not payloads:
        provenance.write_table(
            "similarity_summary", COLUMNS, [], script=script, raw_files=[], pending=PENDING
        )
        out_statement.write_text(statement([]), encoding="utf-8")
        return
    rows = summarize(collect_scores(payloads, cfg), cfg)
    provenance.write_table("similarity_summary", COLUMNS, rows, script=script, raw_files=raw)
    out_statement.write_text(statement(rows), encoding="utf-8")
    charts.save_figure(draw(rows), FIGURE, parity_note=parity.PARITY_NOTE, size="default")


def main() -> int:
    derive()
    return 0


if __name__ == "__main__":
    sys.exit(main())
